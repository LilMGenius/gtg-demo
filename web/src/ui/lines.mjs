// 뽑은 문장은 게시물에 박아 저장한다. 열 때마다 다시 뽑으면 과거 글이 매번 바뀐다.
export function postLine(name, conceded, rng) {
  const pool = POSTS[conceded ? 'conceded' : 'saved'];
  return pool[Math.floor(rng() * pool.length) % pool.length].replace('{n}', name);
}

