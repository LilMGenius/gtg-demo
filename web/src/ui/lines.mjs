/* 눈맞음의 갈래. 지금까지 행인과 눈이 마주치면 언제나 하트 하나에 같은 자세였다.
   한 사건이 늘 같은 그림이면 그 사건은 두 번째부터 정보가 없고, 세 번째부터는 로딩 화면이다.
   갈래마다 자막과 자세와 머리 위 표시가 같이 갈린다. 셋 중 하나만 갈리면 나머지가 그 갈래를 배신한다.
   판정은 안 건드린다. 먹히는 것도 라포가 쌓이는 것도 그대로이고 갈리는 것은 화면뿐이다.
   그래서 갈래는 판정 rng가 아니라 화면 쪽 난수가 뽑는다. 판정 난수를 쓰면 그 뒤 모든 구가 밀린다. */
export const GAZE_ACTS = [
  { id: 'stare', mood: 'heart' },
  { id: 'selfie', mood: 'heart' },
  { id: 'piggy', mood: 'heart' },
  { id: 'hug', mood: 'heart' },
  { id: 'kneel', mood: 'heart' },
  { id: 'crawl', mood: 'shock' },
  { id: 'follow', mood: 'heart' },
  { id: 'joke', mood: 'grin' },
  { id: 'wave', mood: 'grin' }
];

export function gazeAct(rng) {
  return GAZE_ACTS[Math.floor(rng() * GAZE_ACTS.length) % GAZE_ACTS.length].id;
}

export function gazeMood(id) {
  const found = GAZE_ACTS.find((a) => a.id === id);
  return found ? found.mood : 'heart';
}

// 같은 사건 이름이 다른 상황에서 두 번 쓰이는 자리만 갈라 준다.
// ctx.downed는 앞선 사건이 남긴 문맥이고, 이벤트 하나만 봐서는 알 수 없다.
export function lineKey(e, ctx) {
  if (e.t === 'miss' || e.t === 'rebound') return e.t + ':' + e.cause;
  if (e.t === 'reboundMiss' && ctx && ctx.downed) return 'reboundMiss:downed';
  // 눈맞음은 갈래마다 다른 짓을 한다. 자막이 자세를 안 따라가면 둘이 서로를 배신한다.
  if ((e.t === 'distracted' || e.t === 'talked') && e.act) return e.t + ':' + e.act;
  return e.t;
}

// last를 받아 같은 문장을 연달아 내지 않는다. callout.mjs의 aimLine과 같은 규칙이다.
export function eventLine(e, rng, last, ctx) {
  const pool = POOLS[lineKey(e, ctx)];
  if (!pool) return e.line;
  const fresh = pool.filter((s) => s !== last);
  const pick = fresh.length ? fresh : pool;
  return pick[Math.floor(rng() * pick.length) % pick.length];
}

