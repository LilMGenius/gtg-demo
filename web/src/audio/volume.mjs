// 믹스는 코드가 소유한다.
// 화면에 음량 슬라이더가 없으므로 저장된 믹스는 지난 구현이 남긴 잔재뿐이다.
// 잔재가 남은 브라우저는 새 믹스를 영영 받지 못한다.
// bgm 0.10과 sfx 0.70이 남은 브라우저에서 발소리는 베드보다 11.3dB 아래였다.
// 새 브라우저로 재보면 9.4dB 위로 잘만 들렸다. 소리가 안 난다는 신고의 정체가 이것이었다.
// 음소거는 음량과 따로 산다. 음소거 버튼은 화면에 있으므로 그것만 저장된다.
export function readVolume(key, fallback) {
  localStorage.removeItem(key);
  return fallback;
}
